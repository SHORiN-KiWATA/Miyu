//! What lives under `MIYU_HOME`, and whether it travels.
//!
//! Every path Miyu writes must appear in [`UNITS`] — including the ones that
//! must *never* be exported. A hard-coded "list of things to back up" rots
//! silently: someone adds a feature, forgets the export path, and the user
//! only finds out on the new machine when the data is gone. Here the omission
//! is caught by `every_data_location_is_classified` instead.
//!
//! Adding a data location = adding one row. Deciding it should not travel is
//! still a row (`Tier::Never`) with the reason written down.

/// How a unit is copied.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum UnitKind {
    File,
    Dir,
    /// Snapshotted with `VACUUM INTO` rather than copied: the daemon holds
    /// these open with a live WAL, so a plain copy can be torn or stale.
    Sqlite,
}

/// Which export tiers include a unit.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tier {
    /// Exported by default.
    Core,
    /// Large and rebuildable; needs `--index`.
    Heavy,
    /// Platform conversation data; needs `--platforms`.
    Platform,
    /// Never exported. The `why` field says why.
    Never,
}

pub struct DataUnit {
    /// Stable identity, recorded in the manifest. Renaming `rel` must not
    /// change this — it is how a future build recognises an old archive.
    pub id: &'static str,
    /// Path relative to `MIYU_HOME`. A trailing `/*` means "each child of this
    /// directory", used where the children are per-persona or per-platform.
    pub rel: &'static str,
    pub kind: UnitKind,
    pub tier: Tier,
    /// Carries credentials; `--no-secrets` redacts or drops it.
    pub secret: bool,
    /// Why this classification. Required for `Never` so a future reader can
    /// tell a deliberate exclusion from an oversight.
    pub why: &'static str,
}

