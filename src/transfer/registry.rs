/// Suffixes that are never their own unit: SQLite sidecars are folded into the
/// snapshot of their database, and editor/backup droppings are noise.
pub const IGNORED_SUFFIXES: &[&str] = &["-wal", "-shm", ".bak", ".tmp", ".lock"];

/// True when `name` is a backup dropping like `config.jsonc.bak-20260802-011956`.
pub fn is_backup_name(name: &str) -> bool {
    name.contains(".bak")
}

impl DataUnit {
    /// Whether this unit is included for the given tier switches.
    pub fn included(&self, all: bool, index: bool, platforms: bool) -> bool {
        match self.tier {
            Tier::Never => false,
            Tier::Core => true,
            Tier::Heavy => all || index,
            Tier::Platform => all || platforms,
        }
    }

    /// Path segments of `rel`, with `*` marking a wildcard level.
    pub fn segments(&self) -> impl Iterator<Item = &'static str> {
        self.rel.split('/')
    }
}

/// Finds the unit that claims `rel` (a path relative to `MIYU_HOME`), matching
/// `*` against any single segment. A path under a directory unit is claimed by
/// that unit.
pub fn unit_for(rel: &str) -> Option<&'static DataUnit> {
    let parts: Vec<&str> = rel.split('/').filter(|part| !part.is_empty()).collect();
    UNITS.iter().find(|unit| {
        let pattern: Vec<&str> = unit.segments().collect();
        // A directory unit claims everything beneath it, so the path may be
        // longer than the pattern; it may never be shorter.
        if parts.len() < pattern.len() {
            return false;
        }
        pattern
            .iter()
            .zip(parts.iter())
            .all(|(want, have)| *want == "*" || want == have)
    })
}
